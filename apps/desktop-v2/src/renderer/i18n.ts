export const language: "ja" | "en" = navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
const strings: Record<Key, string> = language === "ja" ? ja : en;

export const t = (key: Key) => strings[key];

/** The message for an error code; codes from IPC rejections arrive wrapped as "…: Error: <code>". */
export function errorMessage(code: string | undefined) {
  if (!code) return "";
  const messages = errors[language];
  const key = Object.keys(messages).find((item) => code === item || code.endsWith(`: ${item}`));
  if (key) return messages[key];
  const status = /http(\d+)$/.exec(code)?.[1];
  return status ? `${messages.failed} (HTTP ${status})` : messages.failed;
}

